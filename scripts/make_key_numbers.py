#!/usr/bin/env python3
"""Generate poster_materials/KEY_NUMBERS.md from the committed result files (no hand-typed numbers).

  python scripts/make_key_numbers.py          # (re)write poster_materials/KEY_NUMBERS.md
  python scripts/make_key_numbers.py --check  # exit 1 if the committed file is out of date

Reads: runs/full_20261017T223452Z/manifest.json, results/reanalysis.json, results/report_numbers.json,
results/post_hoc/content_only_baseline.json. Each line says whether its quantity is pre-registered, post hoc, or a
descriptive count of saved results.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "poster_materials" / "KEY_NUMBERS.md"
ORDER = ("s_single", "s_redundant", "s_conflict", "macro_a", "macro_b", "macro_c")
NAMES = {"s_single": "S-single", "s_redundant": "S-redundant", "s_conflict": "S-conflict",
         "macro_a": "Macro A", "macro_b": "Macro B", "macro_c": "Macro C"}


def load(rel):
    return json.loads((ROOT / rel).read_text())


def f3(x):
    return f"{x:.3f}"


def rng(d):
    return f"{d['mean']:+.3f} [{d['min']:+.3f}, {d['max']:+.3f}]"


def s_conflict_counts(R):
    """Cells containing both E1 and E2: does the label follow the precedence rule / the later record?"""
    s = R["scenarios"]["s_conflict"]
    n = rule = later = 0
    for o in s["per_ordering"]:
        pos = s["order_positions"][str(o["ordering"])]
        for key, lab in o["argmax"].items():
            members = set(key.split("+")) if key != "none" else set()
            if {"E1", "E2"} <= members:
                n += 1
                rule += lab == "Positive"
                later_rec = "E1" if pos["E1"] > pos["E2"] else "E2"
                later += lab == ("Positive" if later_rec == "E1" else "Negative")
    return n, rule, later


def build():
    M = load("runs/full_20261017T223452Z/manifest.json")
    R = load("results/reanalysis.json")
    N = load("results/report_numbers.json")
    B = load("results/post_hoc/content_only_baseline.json")
    P, H = N["pre_registered"], N["post_hoc"]
    L = []
    w = L.append

    w("# Key numbers (verified)")
    w("")
    w("Generated by `scripts/make_key_numbers.py` from the committed result files; do not edit by hand.")
    w("Run `python scripts/make_key_numbers.py --check` to confirm this file matches the data.")
    w("")
    w("**Tags.** [pre-registered] = defined before the run (protocol, approval packet, frozen criteria). "
      "[post hoc] = exploratory, defined after the data were seen; it qualifies the pre-registered results and "
      "never replaces them. [descriptive] = a count or comparison read directly from the saved results, with no "
      "pre-registered pass/fail rule.")
    w("")
    w("**How to state uncertainty.** The unit of evidence is the **scenario (n = 6)**: 3 designed controls and "
      "3 realistic cases. The 288 scored prompts are 6 scenarios × 16 evidence subsets × 3 fixed orderings — "
      "deterministic, structured measurements, **not 288 independent samples**. Ranges [min, max] are across the "
      "3 orderings and show ordering sensitivity; they are **not confidence intervals**. No significance tests "
      "were run.")
    w("")

    sc = M["scorer"]
    w("## 1. What was run")
    w("")
    w(f"- Model: `{sc['model_name']}` @ `{sc['commit_hash']}` ({sc['dtype']}), {sc['device_name']}, "
      f"torch {sc['torch_version']}, transformers {sc['transformers_version']}. Run `{M['run_id']}`, "
      f"{M['elapsed_seconds']:,.1f} s.")
    w("- 6 scenarios × 4 evidence records → 16 subsets × 3 fixed orderings = 48 scored prompts per scenario "
      "(288 in total). 9 counterfactual flip prompts (1 per realistic scenario × 3 orderings).")
    pc = P["_pooled_citations"]
    w(f"- Citation stage: {pc['sampled_total']} sampled replies (temperature 1.0, 40 tokens) + {pc['greedy_total']} "
      "greedy replies, parsed by a strict, frozen JSON-list parser.")
    w("")

    w("## 2. The measurement works (validation)")
    w("")
    infra_ok = sum(all(v for k, v in P[s]["infra"].items() if k.startswith("I")) for s in ORDER)
    min_mass = min(P[s]["infra"]["_min_label_mass"] for s in ORDER)
    max_rc = max(P[s]["infra"]["_max_recompute_diff"] for s in ORDER)
    cmp_ = R["comparison_with_pipeline"]
    max_phi_diff = max(v["max_abs_diff_shapley"] for v in cmp_.values())
    all_equal = all(v["checks_equal"] and v["citation_status_equal"] and v["citation_consistency_equal"] and v["d_star_equal"]
                    for v in cmp_.values())
    w(f"- [pre-registered] Infrastructure checks I1–I9 pass in **{infra_ok}/6** scenarios "
      f"(min label probability mass {min_mass:.3f} ≥ 0.95; max first-token recompute difference {max_rc:.1e} ≤ 1e-3).")
    w(f"- Independent re-implementation (separate code) reproduces every saved probability, Shapley value, check and "
      f"citation score: largest Shapley difference **{max_phi_diff:.1e}**; checks and citation scores identical: {all_equal}.")
    for s in ("s_single", "s_redundant", "s_conflict"):
        ch = P[s]["checks"]
        failed = [k for k, v in ch.items() if not v]
        w(f"- [pre-registered] {NAMES[s]} recovery checks: " + ("**all pass** (" + ", ".join(ch) + ")" if not failed
          else f"**FAIL** — {', '.join(failed)} fail; " + ", ".join(k for k in ch if ch[k]) + " pass"))
    w("")

    w("## 3. Shapley values reveal redundancy that leave-one-out misses")
    w("")
    w("| Scenario | Record | Shapley mean [range] | Leave-one-out mean [range] |")
    w("|---|---|---|---|")
    for s, recs in (("s_redundant", ("E1", "E3")), ("macro_c", ("E2", "E3", "E4"))):
        for e in recs:
            w(f"| {NAMES[s]} | {e} | {rng(P[s]['shapley'][e])} | {rng(P[s]['loo'][e])} |")
    w("")
    w("[pre-registered quantities] In S-redundant each of two official reports is sufficient alone, so removing one "
      "changes almost nothing (leave-one-out ≈ 0), while Shapley splits the effect between them.")
    w("")

    n, rule, later = s_conflict_counts(R)
    sc_ = P["s_conflict"]
    w("## 4. The conflict control fails: order, not the stated rule, decides")
    w("")
    w(f"- [pre-registered] S-conflict full-evidence argmax by ordering: {', '.join(sc_['full_argmax_per_ordering'])} "
      f"(designed answer: Positive in every ordering).")
    w(f"- Cells containing both conflicting records: **{n}**. The instructed precedence rule holds in **{rule}/{n}**; "
      f"the label follows whichever of the two records appears **later** in **{later}/{n}**. "
      "[descriptive]")
    w("- Caveat: only 1 of the 3 fixed orderings puts the rate-cut record after the inflation record, so "
      "\"later record wins\" is one contrast (confounded with last position and adjacency), not a replicated effect.")
    w(f"- [pre-registered flags] φ(E1) and φ(E2) ranges across orderings: "
      f"{P['s_conflict']['shapley']['E1']['max'] - P['s_conflict']['shapley']['E1']['min']:.3f} and "
      f"{P['s_conflict']['shapley']['E2']['max'] - P['s_conflict']['shapley']['E2']['min']:.3f} (flag threshold 0.10).")
    w("")

    ma = P["macro_a"]
    md = ma["mean_full_dist"]
    w("## 5. Realistic scenarios: right sign, different weights; one fragile decision")
    w("")
    n_match = sum(P[s]["d_star"] == P[s]["reference"] for s in ORDER)
    signs = [(P[s]["shapley"][e]["mean"] > 0) == (P[s]["rubric_ideal_shapley"][e] > 0)
             for s in ("macro_a", "macro_b", "macro_c") for e in P[s]["rubric_ideal_shapley"]]
    w(f"- [pre-registered] d\\* matches the designed (controls) or rubric (realistic) answer in **{n_match}/6** scenarios.")
    w(f"- [descriptive; rubric-following values fixed before the run] Shapley signs match the rubric for "
      f"**{sum(signs)}/{len(signs)}** realistic records.")
    w(f"- [pre-registered quantities] Macro A full-evidence argmax by ordering: {', '.join(ma['full_argmax_per_ordering'])}; d\\* = Positive by a mean "
      f"margin of **{md['Positive'] - md['Neutral']:.3f}** over Neutral.")
    w(f"- [descriptive] Macro A contrary record (PMI contraction): Shapley **{rng(ma['shapley']['E3'])}** vs rubric-following "
      f"{ma['rubric_ideal_shapley']['E3']:+.2f}.")
    mc = P["macro_c"]
    w(f"- [descriptive] Macro C salient rate cut: Shapley **{rng(mc['shapley']['E1'])}** vs rubric-following "
      f"{mc['rubric_ideal_shapley']['E1']:+.2f} (effectively ignored).")
    pe = [P[s]["v_empty"]["max"] for s in ("macro_a", "macro_b", "macro_c")]
    w(f"- [pre-registered flag] No prior dominance: P(d\\* | no records) ≤ {max(pe):.3f} (flag at 0.70).")
    w("")

    w("## 6. Counterfactual flips move probabilities more than labels")
    w("")
    fl = [P[s]["flip_summary"] for s in ("macro_a", "macro_b", "macro_c")]
    allf = [x for s in ("macro_a", "macro_b", "macro_c") for x in P[s]["flip_summary"]["delta_p_dstar"]["per_ordering"]]
    w(f"- [post hoc, descriptive] P(d\\*) falls in **{sum(x['p_dstar_decreased'] for x in fl)}/9** flip cells "
      f"(ΔP(d\\*) from {min(allf):+.3f} to {max(allf):+.3f}); P(Neutral) rises in "
      f"{sum(x['p_neutral_increased'] for x in fl)}/9.")
    w(f"- [descriptive] The label changes in only **{sum(x['label_changed'] for x in fl)}/9**.")
    c4 = {NAMES[s]: P[s]["flip_summary"]["pre_registered_C4_all_orderings"] for s in ("macro_a", "macro_b", "macro_c")}
    w("- [pre-registered] C4 (label moves away from d\\* in all 3 orderings): "
      + "; ".join(f"{k} {'holds' if v else 'does not hold'}" for k, v in c4.items())
      + " (Macro A partly trivially: ordering 0 was already Neutral).")
    w("")

    w("## 7. Self-reported citations")
    w("")
    al = pc["all"]
    gs = pc["greedy_status"]
    w(f"- [pre-registered] Analyzable replies: {al['n_analyzable']}/{pc['sampled_total']} sampled "
      f"({pc['sampled_status'].get('unparseable', 0)} unparseable), {sum(gs.get(k, 0) for k in ('ok', 'empty'))}/"
      f"{pc['greedy_total']} greedy.")
    w(f"- [pre-registered] Partial citations (n = {al['n_partial']}) beat same-size alternative sets: necessity mean "
      f"**{f3(al['mean_beat_nec'])}** ({round(al['share_beat_nec_gt_half'] * al['n_partial'])}/{al['n_partial']} above chance), "
      f"sufficiency mean **{f3(al['mean_beat_suf'])}** ({round(al['share_beat_suf_gt_half'] * al['n_partial'])}/"
      f"{al['n_partial']} above chance); Shapley top-k agreement {f3(al['mean_topk'])}. Chance = 0.5.")
    sets = {s: P[s]["citations"]["sampled_sets"] for s in ("s_single", "s_redundant", "s_conflict")}
    nsamp = {s: P[s]["citations"]["all"]["n_analyzable"] for s in sets}
    w(f"- [descriptive] Designed controls, parsed sampled replies citing the designed faithful set: S-single {sets['s_single'].get('E2', 0)}/"
      f"{nsamp['s_single']}; S-redundant {sets['s_redundant'].get('E1+E3', 0) + sets['s_redundant'].get('E1', 0) + sets['s_redundant'].get('E3', 0)}/"
      f"{nsamp['s_redundant']}; S-conflict **{sets['s_conflict'].get('E1', 0)}/{nsamp['s_conflict']}** "
      f"(most common: E1+E2, {sets['s_conflict'].get('E1+E2', 0)}/{nsamp['s_conflict']}).")
    mis = sum(len(P[s]["misaligned_orderings"]) for s in ORDER)
    w(f"- [descriptive] **Decision mismatch:** in **{mis}/18** scenario-orderings the label shown to the model in the citation prompt "
      "(the ordering-averaged d\\*) was not the model's own answer for that ordering (S-conflict orderings 0 and 1, "
      "Macro A ordering 0).")
    a_, m_ = H["aligned_only_pooled"], H["misaligned_only_pooled"]
    w(f"- [post hoc] Aligned orderings: n = {a_['n_partial']} partial, beat {f3(a_['mean_beat_nec'])} / "
      f"{f3(a_['mean_beat_suf'])}. Misaligned: n = {m_['n_partial']}, beat {f3(m_['mean_beat_nec'])} / "
      f"{f3(m_['mean_beat_suf'])} ({round(m_['share_beat_nec_gt_half'] * m_['n_partial'])}/{m_['n_partial']} and "
      f"{round(m_['share_beat_suf_gt_half'] * m_['n_partial'])}/{m_['n_partial']} above chance): lower on average, but "
      "still above chance for a label the model did not choose in that ordering.")
    rows = [r for r in H["own_decision_rescoring"]["rows"] if r["category"] == "partial"]
    mean = lambda k: sum(r[k] for r in rows) / len(rows)  # noqa: E731
    w(f"- [post hoc] Rescoring those {len(rows)} misaligned partial citations against the model's own decision: "
      f"{f3(mean('beat_nec_injected'))} / {f3(mean('beat_suf_injected'))} → **{f3(mean('beat_nec_own'))} / "
      f"{f3(mean('beat_suf_own'))}** (necessity / sufficiency). Not a valid fix: it asks a question the model was not asked.")
    w("")

    w("## 8. Post hoc: a content-only citer that never looks at the model")
    w("")
    pb = B["pooled"]
    cb, mb = pb["content_only_18_ordering_citations"], pb["model_pre_registered_40_partial_sampled"]
    cm = pb["scenario_metric_comparisons"]
    w("Rule (defined after the results were seen): cite the designed faithful set (controls) or the "
      "records whose rubric score supports the reference answer (realistic). It never observes the model's behavior, but "
      "it uses the experimenter's design and rubric. Not like-for-like: one fixed set per scenario vs the model's sampled "
      "citations.")
    w("")
    w("| | Necessity beat | Sufficiency beat | Shapley top-k |")
    w("|---|---|---|---|")
    w(f"| Content-only citer (18 scenario-orderings) | {f3(cb['mean_beat_nec'])} | {f3(cb['mean_beat_suf'])} | {f3(cb['mean_topk'])} |")
    w(f"| Phi-3's own citations (40 partial) | {f3(mb['mean_beat_nec'])} | {f3(mb['mean_beat_suf'])} | {f3(mb['mean_topk'])} |")
    w("")
    ex = cm["exceptions"]
    hi = tie = 0
    for sid in ORDER:
        for k in ("mean_beat_nec", "mean_beat_suf", "mean_topk"):
            c_, m_v = B["scenarios"][sid]["content_only"][k], B["scenarios"][sid]["model_pre_registered"][k]
            tie += abs(c_ - m_v) <= 1e-12
            hi += c_ > m_v + 1e-12
    w(f"- Content-only ≥ model in **{cm['content_only_ge_model']}/{cm['of']}** scenario × metric comparisons (higher in {hi}, "
      f"tied in {tie}, lower in {cm['of'] - hi - tie}); exception: "
      + "; ".join(f"{NAMES[e['scenario']]} {e['metric'].replace('mean_beat_', '')} {f3(e['content_only'])} vs {f3(e['model'])}" for e in ex)
      + ". Descriptive only; no test.")
    eq = pb["model_citations_equal_to_content_set"]
    w(f"- The model's analyzable citations equal the content-only set in {eq['n']}/{eq['of']} cases (sampled + greedy).")
    w("- Implication: these metrics reward citing records whose *content* supports the answer. High scores are "
      "therefore not, by themselves, evidence that the model is reporting what drove its own decision.")
    w("")
    w("## Per-scenario summary")
    w("")
    w("| Scenario | Kind | d\\* | Matches design/rubric | Recovery checks | C1 nec. (n) | C2 suf. (n) | C3 top-k | Content-only nec./suf./top-k |")
    w("|---|---|---|---|---|---|---|---|---|")
    for s in ORDER:
        p = P[s]
        ch = p["checks"]
        rc = "n/a (descriptive)" if not ch else ("pass" if all(ch.values()) else "FAIL (" + ", ".join(k for k, v in ch.items() if not v) + ")")
        c = p["citations"]["all"]
        co = B["scenarios"][s]["content_only"]
        w(f"| {NAMES[s]} | {'control' if p['kind'] == 'synthetic_control' else 'realistic'} | {p['d_star']} | "
          f"{'yes' if p['d_star'] == p['reference'] else 'no'} | {rc} | {f3(c['mean_beat_nec'])} ({c['n_partial']}) | "
          f"{f3(c['mean_beat_suf'])} ({c['n_partial']}) | {f3(c['mean_topk'])} | "
          f"{f3(co['mean_beat_nec'])} / {f3(co['mean_beat_suf'])} / {f3(co['mean_topk'])} |")
    w("")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print(f"{OUT.relative_to(ROOT)} is {'up to date' if ok else 'OUT OF DATE (run scripts/make_key_numbers.py)'}")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
